# frozen_string_literal: true

require "open3"
require "set"

module IdiomaticRails
  class DeadCode
    # Asks the application's own Rails which actions are routed and which
    # macros take a method name as a symbol.
    #
    # Both answers used to be hardcoded here, and both were wrong.
    #
    # Parsing config/routes.rb cannot see `patch :publish, on: :member` or
    # `get :suggestions` — the router's DSL has more spellings than a reader
    # keeps up with, and each one it misses reports a live action as dead.
    # The expanded table also carries the controller, which the file does not
    # make easy: matching on action name alone exempts a dead `show` because
    # some *other* controller routes a `show`.
    #
    # The callback list had the same problem in the other direction. It
    # carried `before_validation` but not `before_create`, so one callback in
    # a model was understood and the next one down was reported dead. Rails
    # already publishes the list, and reading it from the booted application
    # means it tracks the Rails version in the Gemfile rather than the one
    # this gem was written against.
    #
    # One boot answers both. It needs no database.
    module RailsFacts
      Facts = Struct.new(:routes, :callbacks, keyword_init: true)

      # Printed with a prefix so one stream carries both answers.
      SCRIPT = <<~RUBY_SCRIPT
        Rails.application.routes.routes.each do |route|
          controller = route.defaults[:controller]
          action = route.defaults[:action]
          next if controller.nil? || action.nil?
          puts "ROUTE \#{controller}#\#{action}"
        end

        if defined?(ActiveRecord::Callbacks::CALLBACKS)
          ActiveRecord::Callbacks::CALLBACKS.each { |name| puts "CALLBACK \#{name}" }
        end

        # after_create_commit and friends are generated from the transaction
        # actions rather than listed, so they are derived the same way Rails
        # derives them.
        if defined?(ActiveRecord::Transactions::ACTIONS)
          ActiveRecord::Transactions::ACTIONS.each do |action|
            puts "CALLBACK after_\#{action}_commit"
          end
          puts "CALLBACK after_save_commit"
        end

        # Controller filters are generated by define_callbacks rather than
        # named in a constant, so they are derived from the filter kinds.
        %w[before after around].each do |kind|
          puts "CALLBACK \#{kind}_action"
          puts "CALLBACK skip_\#{kind}_action"
        end
      RUBY_SCRIPT

      def self.call(root)
        stdout, stderr, status = Open3.capture3("bin/rails", "runner", SCRIPT, chdir: root.to_s)

        unless status.success?
          raise Error, <<~MESSAGE
            Could not read the routes: `bin/rails runner` exited #{status.exitstatus}.

            This check asks Rails which actions are routed and which macros name
            a method, rather than hardcoding either, so the application has to
            boot. It needs no database. If boot requires environment variables,
            set them the way bin/ci does.

            #{stderr.lines.last(5).join.strip}
          MESSAGE
        end

        routes = Set.new
        callbacks = Set.new
        stdout.each_line do |line|
          kind, value = line.strip.split(" ", 2)
          next if value.nil?

          routes << value if kind == "ROUTE"
          callbacks << value.to_sym if kind == "CALLBACK"
        end

        Facts.new(routes: routes, callbacks: callbacks)
      end
    end
  end
end
